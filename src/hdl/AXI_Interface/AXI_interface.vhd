library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use work.gt_pkg.all;
use work.axi_lane_pkg.all;
use work.reg_space_pack.all;

entity AXI_interface is
    generic ( GT_N : integer := 2; DDMTD_N : integer := 2 );
    port( 
        -- Ethernet SFP lane
        eth_gtrefclk_p : in std_logic;
        eth_gtrefclk_n : in std_logic;
        txn_eth_sfp : out std_logic;
        txp_eth_sfp : out std_logic;
        rxn_eth_sfp : in  std_logic;
        rxp_eth_sfp : in  std_logic;
        
        -- Virtex PHY
--        phy_resetb   : out   std_logic;  -- reset signal (inverted)
--        phy_mdio     : inout std_logic;  -- control line to program the PHY chip
--        phy_mdc      : out   std_logic;  -- clock line (must be < 2.5 MHz)
        -- Versal QUAD clock
        apb3clk_quad : in std_logic;
        
        -- Ethernet addresses selection
        eth_addr_sel : in std_logic_vector(2 downto 0);
        
        -- IIC
        sda : inout std_logic;
        scl : inout std_logic;
        
        -- synch and shared data
        clk_sys  : in  std_logic;
        clk_sys_gt  : in  std_logic;
        clk_pcs_pma : in  std_logic; 
        clk_lock    : in  std_logic; 
        rxusrclk : in  std_logic_vector(GT_N-1 downto 0);
        txusrclk : in  std_logic_vector(GT_N-1 downto 0);
        to_axi   : in  to_axi_t;
        from_axi : out from_axi_t
    );
end AXI_interface;

architecture Behavioral of AXI_interface is

    -- AXI MM Interface
    signal resetn_axi    : std_logic; -- generated by the AXI master signal
    
    signal m_axi_lane_awaddr  : axi_lane_awaddr_t;
    signal m_axi_lane_awvalid : axi_lane_awvalid_t;
    signal m_axi_lane_awready : axi_lane_awready_t := (others => '0');
    signal m_axi_lane_wdata   : axi_lane_wdata_t;
    signal m_axi_lane_wstrb   : axi_lane_wstrb_t;
    signal m_axi_lane_wvalid  : axi_lane_wvalid_t;
    signal m_axi_lane_wready  : axi_lane_wready_t  := (others => '0');
    signal m_axi_lane_bresp   : axi_lane_bresp_t   := (others => (others => '0'));
    signal m_axi_lane_bvalid  : axi_lane_bvalid_t  := (others => '0');
    signal m_axi_lane_bready  : axi_lane_bready_t;
    signal m_axi_lane_araddr  : axi_lane_araddr_t;
    signal m_axi_lane_arvalid : axi_lane_arvalid_t;
    signal m_axi_lane_arready : axi_lane_arready_t := (others => '0');
    signal m_axi_lane_rdata   : axi_lane_rdata_t   := (others => (others => '0'));
    signal m_axi_lane_rresp   : axi_lane_rresp_t   := (others => (others => '0'));
    signal m_axi_lane_rvalid  : axi_lane_rvalid_t  := (others => '0');
    signal m_axi_lane_rready  : axi_lane_rready_t;
    
    signal m_axi_aux_awaddr  : std_logic_vector(31 downto 0); 
    signal m_axi_aux_awvalid : std_logic;
    signal m_axi_aux_awready : std_logic                       := '0';            
    signal m_axi_aux_wdata   : std_logic_vector(31 downto 0);
    signal m_axi_aux_wstrb   : std_logic_vector(3 downto 0);
    signal m_axi_aux_wvalid  : std_logic;
    signal m_axi_aux_wready  : std_logic                       := '0';            
    signal m_axi_aux_bresp   : std_logic_vector(1 downto 0)    := (others => '0');
    signal m_axi_aux_bvalid  : std_logic                       := '0';            
    signal m_axi_aux_bready  : std_logic;
    signal m_axi_aux_araddr  : std_logic_vector(31 downto 0);
    signal m_axi_aux_arvalid : std_logic;
    signal m_axi_aux_arready : std_logic                       := '0';            
    signal m_axi_aux_rdata   : std_logic_vector(31 downto 0)   := (others => '0');
    signal m_axi_aux_rresp   : std_logic_vector(1 downto 0)    := (others => '0');
    signal m_axi_aux_rvalid  : std_logic                       := '0';            
    signal m_axi_aux_rready  : std_logic;                                  
    
    signal fsm_aligner_logs      : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    signal fsm_aligner_logs_sys  : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    
    signal gt_logs     : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    signal gt_logs_sys : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    
    signal acc_precal_log_sys : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    signal fifo_fill_log_sys  : register_array_t(GT_N-1 downto 0) := (others => (others => '0'));
    
    signal ctrl_general   : std_logic_vector(31 downto 0) := (others => '0');
    signal ctrl_heat      : std_logic_vector(31 downto 0) := (others => '0');
    signal ctrl_all       : reg_space_t(GT_N-1 downto 0)(31 downto 0) := (others => (others => '0'));
    signal ctrl_gt_side   : reg_space_t(GT_N-1 downto 0)(15 downto 0) := (others => (others => '0'));
    signal ctrl_pi_side   : reg_space_t(GT_N-1 downto 0)(15 downto 0) := (others => (others => '0'));

    signal rxalidisable   : std_logic_vector(GT_N-1 downto 0) := (others => '0');
    signal txencbypass    : std_logic_vector(GT_N-1 downto 0) := (others => '0');
    signal txbufstat      : reg_space_t(GT_N-1 downto 0)(1 downto 0) := (others => "00");
    signal temp_sync      : std_logic_vector(31 downto 0) := (others => '0');

    constant USE_RXPI      : integer := 1;
    constant N_REG_TO_AXI  : integer := 1 + GT_N*2 + USE_RXPI*GT_N*5 + GT_N*2 + DDMTD_N*6;  
    constant N_REG_FROM_AXI: integer := 2 + GT_N;
    signal to_axi_array   : reg_space_t(N_REG_TO_AXI  -1 downto 0)(31 downto 0) := (others => (others => '0'));
    signal from_axi_array : reg_space_t(N_REG_FROM_AXI-1 downto 0)(31 downto 0) := (others => (others => '0'));
    signal ctrl_async     : reg_space_t(N_REG_FROM_AXI-1 downto 0)(31 downto 0) := (others => (others => '0'));
    
begin

    to_axi_signals: for i in 0 to GT_N-1 generate
        -- to_axi Array - logs and data to Python 
        -- FSM_ALIGNER_LOGS
        fsm_aligner_logs(i)(8 downto 0)   <= to_axi.from_gt(i).logic.slide_count;
        fsm_aligner_logs(i)(17 downto 9)  <= to_axi.from_gt(i).logic.lol_count;
        fsm_aligner_logs(i)(26 downto 18) <= to_axi.from_gt(i).logic.odds_count;
        fsm_aligner_logs(i)(27)           <= to_axi.from_gt(i).logic.data_valid;
        fsm_aligner_logs(i)(28)           <= to_axi.from_gt(i).logic.rx_aligned;
    
        -- GT_LOGS - async (clk_sys)
        gt_logs(i)(0) <= to_axi.from_gt(i).txpi.ali_done;
        gt_logs(i)(1) <= to_axi.from_gt(i).txpi.step_done;
        gt_logs(i)(2) <= to_axi.from_gt(i).tx_rdy;
        gt_logs(i)(4 downto 3) <= to_axi.from_gt(i).txbufstatus;
        gt_logs(i)(5) <= to_axi.from_gt(i).pslverr_o;
        gt_logs(i)(6) <= to_axi.from_gt(i).timeout  ;
        gt_logs(i)(15 downto 7) <= (others => '0');
        gt_logs(i)(31 downto 16) <= to_axi.from_gt(i).txpi.acc_phase;
        
        bus_synch_rx_to_axi: entity work.vec_sync
            generic map ( N_BITS => 32 ) 
            port map (
                src_clk  => '0',
                clk      => clk_sys,
                async_in => fsm_aligner_logs(i),   
                sync_out => fsm_aligner_logs_sys(i)
            );
        bus_synch_gt_to_axi: entity work.vec_sync
            generic map ( N_BITS => 32 ) 
            port map (
                src_clk  => '0',
                clk      => clk_sys,
                async_in => gt_logs(i),   
                sync_out => gt_logs_sys(i)
            );
         bus_synch_gt2_to_axi: entity work.vec_sync
           generic map ( N_BITS => 16 ) 
           port map (
             src_clk  => '0',
             clk      => clk_sys,
             async_in => to_axi.from_gt(i).txpi.acc_phase_pre_cal, 
             sync_out => acc_precal_log_sys(i)(15 downto 0)
           );
        bus_synch_gt3_to_axi: entity work.vec_sync
           generic map ( N_BITS => 32 ) 
           port map (
             src_clk  => '0',
             clk      => clk_sys,
             async_in => to_axi.from_gt(i).txpi.fifo_fill_pd, 
             sync_out => fifo_fill_log_sys(i)
           );
      
    end generate to_axi_signals;
    
    bus_synch_temp_to_axi: entity work.vec_sync
        generic map ( N_BITS => 32 ) 
        port map (
            src_clk  => '0',
            clk      => clk_sys,
            async_in => to_axi.temp,
            sync_out => temp_sync  
        );
    
    -- TO_AXI - async (clk_sys)
    
    to_axi_array(0) <= temp_sync; -- Address: 0x00000000
    
    gt_logs_gen : for i in 0 to GT_N-1 generate -- base address: 4
      to_axi_array(2*i + 1) <= fsm_aligner_logs_sys(i); -- Address: 8*i + 4
      to_axi_array(2*i + 2) <= gt_logs_sys(i);          -- Address: 8*i + 8
    end generate gt_logs_gen; -- next free address = 8*GT_N + 4
    
    dmon_logs_gen : for i in 0 to GT_N-1 generate -- base address: 8*GT_N + 4
      to_axi_array((2*GT_N + 1) + 5*i + 0) <= to_axi.from_rxpi(i).single; -- Address: (8*GT_N + 4) + 20*i
      to_axi_array((2*GT_N + 1) + 5*i + 1) <= to_axi.from_rxpi(i).sum;    -- Address: (8*GT_N + 4) + 20*i + 4
      to_axi_array((2*GT_N + 1) + 5*i + 2) <= to_axi.from_rxpi(i).var;    -- Address: (8*GT_N + 4) + 20*i + 8
      to_axi_array((2*GT_N + 1) + 5*i + 3) <= to_axi.from_rxpi(i).max;    -- Address: (8*GT_N + 4) + 20*i + 12
      to_axi_array((2*GT_N + 1) + 5*i + 4) <= to_axi.from_rxpi(i).min;    -- Address: (8*GT_N + 4) + 20*i + 16
    end generate dmon_logs_gen; -- next free address = 28*GT_N + 4
    
    -- TXPI extra GT logs immediately after DMON (2 regs per GT), before DMTD
    -- base index  = 1 + 7*GT_N
    -- base address = 28*GT_N + 4
    txpi_extra_logs_gen : for i in 0 to GT_N-1 generate
      to_axi_array((7*GT_N + 1) + 2*i + 0) <= fifo_fill_log_sys(i);  -- Address: (28*GT_N + 4) + 8*i
      to_axi_array((7*GT_N + 1) + 2*i + 1) <= acc_precal_log_sys(i); -- Address: (28*GT_N + 4) + 8*i + 4
    end generate txpi_extra_logs_gen; -- next free address = 36*GT_N + 4
    
    posdmtd: if DDMTD_N > 0 generate
        dmtd_logs_gen : for i in 0 to DDMTD_N-1 generate -- base address: 36*GT_N + 4
          to_axi_array((9*GT_N + 1) + 6*i + 0) <= to_axi.from_dmtds(i).phase_count; -- Address: (36*GT_N + 4) + 24*i
          to_axi_array((9*GT_N + 1) + 6*i + 1) <= to_axi.from_dmtds(i).glitches;    -- Address: (36*GT_N + 4) + 24*i + 4
          to_axi_array((9*GT_N + 1) + 6*i + 2) <= to_axi.from_dmtds(i).phase_avg;   -- Address: (36*GT_N + 4) + 24*i + 8
          to_axi_array((9*GT_N + 1) + 6*i + 3) <= to_axi.from_dmtds(i).stdv;        -- Address: (36*GT_N + 4) + 24*i + 12
          to_axi_array((9*GT_N + 1) + 6*i + 4) <= to_axi.from_dmtds(i).max;         -- Address: (36*GT_N + 4) + 24*i + 16
          to_axi_array((9*GT_N + 1) + 6*i + 5) <= to_axi.from_dmtds(i).min;         -- Address: (36*GT_N + 4) + 24*i + 20
        end generate dmtd_logs_gen; -- next free address = 36*GT_N + 24*DDMTD_N + 4
    end generate posdmtd;
        
    -- from_axi Array - control signals from Python
    -- CTRL

    ctrl_async_gen : for i in 0 to 2 + GT_N-1 generate
      ctrl_async(i) <= from_axi_array(i);  -- Address: 0x10000000 + 4*i
    end generate ctrl_async_gen;
    
    bus_synch_axi_to_gt_sys_d: entity work.vec_sync
        generic map ( N_BITS => 32 ) 
        port map (
            src_clk  => '0',
            clk      => clk_sys_gt,
            async_in => ctrl_async(0),
            sync_out => ctrl_general    -- Address: 0x10000000
        );
    bus_synch_axi_to_gt_sys_t: entity work.vec_sync
        generic map ( N_BITS => 32 ) 
        port map (
            src_clk  => '0',
            clk      => clk_sys_gt,
            async_in => ctrl_async(1),
            sync_out => ctrl_heat       -- Address: 0x10000004
        );
    
    from_axi.heat_ctrl     <= ctrl_heat(19 downto 0);  
    from_axi.heater_enable <= ctrl_general(0); -- synchronized inside heater wrapper
    from_axi_dmtd_rst: for i in 0 to DDMTD_N-1 generate
        from_axi.dmtd_hold_rst(i) <= ctrl_general(i+1); -- synchronized inside ddmtd wrapper
    end generate from_axi_dmtd_rst;
          
    from_axi_signals: for i in 0 to GT_N-1 generate
    
       bus_synch_axi_to_gt_sys_1: entity work.vec_sync
         generic map ( N_BITS => 32 ) 
         port map (
             src_clk  => '0',
             clk      => clk_sys_gt,
             async_in => ctrl_async(i+2),
             sync_out => ctrl_all(i)     
         );
       
       ctrl_gt_side(i) <= ctrl_all(i)(15 downto  0);
       ctrl_pi_side(i) <= ctrl_all(i)(31 downto 16);
       
       -- GT controls
       from_axi.to_gt(i).rx_reset      <= ctrl_gt_side(i)(0);   -- async (clk_sys)
       from_axi.to_gt(i).tx_reset      <= ctrl_gt_side(i)(1);   -- async (clk_sys)
       from_axi.to_gt(i).rx_aligner_en <= not(rxalidisable(i)); -- ctrl_gt_side(i)(2) synched to rxusrclk(i)
       from_axi.to_gt(i).tx_enc_bypass <= txencbypass(i);       -- ctrl_gt_side(i)(3) synched to txusrclk(i)
       from_axi.to_gt(i).reset_all     <= ctrl_gt_side(i)(4);   -- async (clk_sys)
       from_axi.to_gt(i).rx_reset_dp   <= ctrl_gt_side(i)(5);   -- async (clk_sys)
       from_axi.to_gt(i).tx_reset_dp   <= ctrl_gt_side(i)(6);   -- async (clk_sys)
       
       -- GT Equalizer - async (clk_sys)
       from_axi.to_gt(i).gt_eq.lpmgc <= ctrl_gt_side(i)(15 downto 14); -- {gt_ctrl.rxlpmgchold   , gt_ctrl.rxlpmgcovrden  }
       from_axi.to_gt(i).gt_eq.lpmhf <= ctrl_gt_side(i)(13 downto 12); -- {gt_ctrl.rxlpmhfhold   , gt_ctrl.rxlpmhfovrden  }
       from_axi.to_gt(i).gt_eq.lpmlf <= ctrl_gt_side(i)(11 downto 10); -- {gt_ctrl.rxlpmlfklhold , gt_ctrl.rxlpmlfklovrden}
       from_axi.to_gt(i).gt_eq.lpmos <= ctrl_gt_side(i)( 9 downto  8); -- {gt_ctrl.rxlpmoshold   , gt_ctrl.rxlpmosovrden  }
       
       -- TxPI Ctrl - async (clk_sys)
       from_axi.to_gt(i).txpi.fine_realign <= ctrl_pi_side(i)(1);
       from_axi.to_gt(i).txpi.ali_calib    <= ctrl_pi_side(i)(2);
       from_axi.to_gt(i).txpi.hold_rst     <= ctrl_pi_side(i)(3);
       from_axi.to_gt(i).txpi.ctrl         <= ctrl_pi_side(i)(11 downto 4);
       from_axi.to_gt(i).txpi.skip_ali     <= ctrl_pi_side(i)(12);
       from_axi.to_gt(i).txpi.nUI          <= ctrl_pi_side(i)(15 downto 13);
       
       bit_synch_axi_to_rx: entity work.bit_sync
            port map (
                clk      => rxusrclk(i),
                async_in => ctrl_gt_side(i)(2),  
                sync_out => rxalidisable(i)      
            ); 
       bit_synch_axi_to_tx: entity work.bit_sync
            port map (
                clk      => txusrclk(i),
                async_in => ctrl_gt_side(i)(3), 
                sync_out => txencbypass(i)      
            ); 
       
    end generate from_axi_signals;

    ----------------------------------------------------------------------------
    -- UDP to AXI Master
    ----------------------------------------------------------------------------
    
    system_ctrl_inst: entity work.system_control
     port map (

        sys_clk_125  => clk_sys,
        
        -- Ethernet lanes
        eth_gtrefclk_p => eth_gtrefclk_p,
        eth_gtrefclk_n => eth_gtrefclk_n,
        txn_eth_sfp => txn_eth_sfp,
        txp_eth_sfp => txp_eth_sfp,
        rxn_eth_sfp => rxn_eth_sfp,
        rxp_eth_sfp => rxp_eth_sfp,
        
        clk_pcs_pma => clk_pcs_pma,
        clk_lock    => clk_lock   ,
        
        apb3clk_quad => apb3clk_quad,
        
        -- Virtex PHY
--        phy_resetb  => phy_resetb,
--        phy_mdio    => phy_mdio,
--        phy_mdc     => phy_mdc,

        eth_addr_sel   => eth_addr_sel,
        ------------------------------------------------------------------------
        -- I2C Master and GPIOs
        ------------------------------------------------------------------------

        -- I2C Interface (Master)
        sda => sda,
        scl => scl,

        -- DEBUG LEDs
        --GPIO_LED : out std_logic_vector(7 downto 0);

        ------------------------------------------------------------------------
        -- Master AXI-Lite interface
        ------------------------------------------------------------------------

        m_axi_resetn => resetn_axi,

        ---- vectors of AXI Interfaces controlling the Data Lanes
        m_axi_lane_awaddr  => m_axi_lane_awaddr, 
        m_axi_lane_awvalid => m_axi_lane_awvalid,
        m_axi_lane_awready => m_axi_lane_awready,
        m_axi_lane_wdata   => m_axi_lane_wdata,  
        m_axi_lane_wstrb   => m_axi_lane_wstrb,  
        m_axi_lane_wvalid  => m_axi_lane_wvalid, 
        m_axi_lane_wready  => m_axi_lane_wready, 
        m_axi_lane_bresp   => m_axi_lane_bresp,  
        m_axi_lane_bvalid  => m_axi_lane_bvalid, 
        m_axi_lane_bready  => m_axi_lane_bready, 
        m_axi_lane_araddr  => m_axi_lane_araddr, 
        m_axi_lane_arvalid => m_axi_lane_arvalid,
        m_axi_lane_arready => m_axi_lane_arready,
        m_axi_lane_rdata   => m_axi_lane_rdata,  
        m_axi_lane_rresp   => m_axi_lane_rresp,  
        m_axi_lane_rvalid  => m_axi_lane_rvalid, 
        m_axi_lane_rready  => m_axi_lane_rready,
        
        ---- Auxiliary Interface
        m_axi_aux_awaddr  => m_axi_aux_awaddr, 
        m_axi_aux_awvalid => m_axi_aux_awvalid,
        m_axi_aux_awready => m_axi_aux_awready,
        m_axi_aux_wdata   => m_axi_aux_wdata,
        m_axi_aux_wstrb   => m_axi_aux_wstrb,  
        m_axi_aux_wvalid  => m_axi_aux_wvalid, 
        m_axi_aux_wready  => m_axi_aux_wready, 
        m_axi_aux_bresp   => m_axi_aux_bresp,  
        m_axi_aux_bvalid  => m_axi_aux_bvalid, 
        m_axi_aux_bready  => m_axi_aux_bready, 
        m_axi_aux_araddr  => m_axi_aux_araddr, 
        m_axi_aux_arvalid => m_axi_aux_arvalid,
        m_axi_aux_arready => m_axi_aux_arready,
        m_axi_aux_rdata   => m_axi_aux_rdata,  
        m_axi_aux_rresp   => m_axi_aux_rresp,  
        m_axi_aux_rvalid  => m_axi_aux_rvalid, 
        m_axi_aux_rready  => m_axi_aux_rready
        
    );
    
    reg_space_read: entity work.axi_register_space  -- Address: 0x00000000
     generic map(
        READ_ONLY => true,
        -- number of 32 bit registers to be allocated (min 1)
        REGISTERS_N => N_REG_TO_AXI
     ) port map (
     
        ---- Reset / Clock
        reset => not(resetn_axi),
        clock => clk_sys,

        ---- Slave AXI-Lite Interface
        s_axi_awaddr  => m_axi_lane_awaddr( 0),   
        s_axi_awvalid => m_axi_lane_awvalid(0),              
        s_axi_awready => m_axi_lane_awready(0),              
        s_axi_wdata   => m_axi_lane_wdata(  0),                
        s_axi_wstrb   => m_axi_lane_wstrb(  0),                
        s_axi_wvalid  => m_axi_lane_wvalid( 0),               
        s_axi_wready  => m_axi_lane_wready( 0),               
        s_axi_bresp   => m_axi_lane_bresp(  0),                
        s_axi_bvalid  => m_axi_lane_bvalid( 0),               
        s_axi_bready  => m_axi_lane_bready( 0),               
        s_axi_araddr  => m_axi_lane_araddr( 0),   
        s_axi_arvalid => m_axi_lane_arvalid(0),              
        s_axi_arready => m_axi_lane_arready(0),              
        s_axi_rdata   => m_axi_lane_rdata(  0),                
        s_axi_rresp   => m_axi_lane_rresp(  0),                
        s_axi_rvalid  => m_axi_lane_rvalid( 0),               
        s_axi_rready  => m_axi_lane_rready( 0),               

        ---- Register Outputs
        reg_space_i => to_axi_array -- IN
    );
    
    reg_space_write: entity work.axi_register_space  -- Address: 0x10000000
     generic map(
        READ_ONLY => false,
        -- number of 32 bit registers to be allocated (min 1)
        REGISTERS_N => N_REG_FROM_AXI
     ) port map (
     
        ---- Reset / Clock
        reset => not(resetn_axi),
        clock => clk_sys,

        ---- Slave AXI-Lite Interface
        s_axi_awaddr  => m_axi_lane_awaddr( 1),   
        s_axi_awvalid => m_axi_lane_awvalid(1),              
        s_axi_awready => m_axi_lane_awready(1),              
        s_axi_wdata   => m_axi_lane_wdata(  1),                
        s_axi_wstrb   => m_axi_lane_wstrb(  1),                
        s_axi_wvalid  => m_axi_lane_wvalid( 1),               
        s_axi_wready  => m_axi_lane_wready( 1),               
        s_axi_bresp   => m_axi_lane_bresp(  1),                
